Rating = int(input("Введите ваше число в рейтинге от 1 до 10: "))

match Rating:
    case 1|2|3:
        print("плохой продукт😫, ужасно, не подойдет никак, не рекомендую!")
    case 4|5|6:
        print("средний продукт🤔, я бы не рекомендовал, но может быть взят в идею")
    case 7|8:
        print("хороший продукт🙂, неплохо, можно взять во внимание")
    case 9|10:
        print("отличный продукт😎, Настоятельно рекомендую!")
    case _:
        print("продукт не в рейтинге")

